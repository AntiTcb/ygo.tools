// Regenerates src/lib/effect-search/vocab.generated.ts from the effect search vocabulary
// tables (effect_vocab_verbs / effect_vocab_zones), so UI code gets compile-time term checks.
//
//   pnpm effect-search:gen-vocab
//
// Needs PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_KEY (loaded from .env.local by the pnpm script).
// The tables are the source of truth: approving a term in /admin works without regenerating;
// regenerate when UI code needs to reference a new term by name.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const OUT = 'src/lib/effect-search/vocab.generated.ts';

const url = process.env.PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_KEY;
if (!url || !key) {
  console.error('Missing PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_KEY');
  process.exit(1);
}

const get = async (path) => {
  const res = await fetch(`${url}/rest/v1/${path}`, { headers: { apikey: key, Authorization: `Bearer ${key}` } });
  if (!res.ok) throw new Error(`${path}: ${res.status} ${await res.text()}`);
  return res.json();
};

const verbs = await get('effect_vocab_verbs?select=term,usable_as_action,usable_as_event&retired_at=is.null&order=id');
const zones = await get('effect_vocab_zones?select=term&retired_at=is.null&order=id');

const list = (terms) => terms.map((t) => `  '${t}',`).join('\n');
const out = `// Generated by scripts/effect-search-gen-vocab.mjs from effect_vocab_verbs / effect_vocab_zones. Do not edit.

export const EFFECT_ACTION_VERBS = [
${list(verbs.filter((v) => v.usable_as_action).map((v) => v.term))}
] as const;

export const EFFECT_EVENT_VERBS = [
${list(verbs.filter((v) => v.usable_as_event).map((v) => v.term))}
] as const;

export const EFFECT_ZONES = [
${list(zones.map((z) => z.term))}
] as const;

export type EffectActionVerb = (typeof EFFECT_ACTION_VERBS)[number];
export type EffectEventVerb = (typeof EFFECT_EVENT_VERBS)[number];
export type EffectVerb = EffectActionVerb | EffectEventVerb;
export type EffectZone = (typeof EFFECT_ZONES)[number];
`;

writeFileSync(OUT, out);
execFileSync(process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm', ['exec', 'oxfmt', OUT], { stdio: 'inherit', shell: process.platform === 'win32' });
console.log(`Wrote ${OUT}: ${verbs.length} verbs, ${zones.length} zones`);
